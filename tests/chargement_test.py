COLS = ["#000000", "#FFFFFF", "#E53935", "#1E88E5"]
def make(path, layers=220, seed=5):
    rnd = random.Random(seed)
    L = ["; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.5.0", "; HEADER_BLOCK_END", "SET_PRINT_AUTO_BED_LEVELING ENABLE=1",
         "PRINT_START", "M104 T0 S140", "G28 X Y", "T0", "G90", "M109 S210 T0", "G1 X10 Y10 E5 F600"]
    cur = 0
    for layer in range(layers):
        L += [";LAYER_CHANGE", ";Z:%.2f" % (0.2 * (layer + 1)), "G1 Z%.2f" % (0.2 * (layer + 1)),
              "M73 P%d R%d" % (int(100 * layer / layers), int(200 * (1 - layer / layers)))]
        for t in rnd.sample(range(4), 2):
            if t != cur:
                L += ["; Change Tool%d -> Tool%d (layer %d)" % (cur, t, layer), "G91", "G1 Z1.5 F600", "G90", "M109 S210 T%d" % t, "M400", "T%d" % t]
                cur = t
            L += ["G1 X%d.%03d Y%d.%03d E0.0%d F3000" % (rnd.randint(10, 200), rnd.randint(0, 999), rnd.randint(10, 200), rnd.randint(0, 999), rnd.randint(10, 99)) for _ in range(90)]
    L += ["PRINT_END", "; filament used [mm] = 900.00,5800.00,640.00,970.00", "; filament used [g] = 27.0,174.0,19.0,29.0",
          "; CONFIG_BLOCK_START", "; filament_colour = " + ";".join(c + "FF" for c in COLS), "; filament_type = PLA;PLA;PLA;PLA",
          "; nozzle_diameter = 0.4,0.4,0.4,0.4", "; CONFIG_BLOCK_END"]
    open(path, "w").write("\n".join(L) + "\n")
