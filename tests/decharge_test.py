def plan_rows(dd):
    """(tête, chargeur latéral ou à la main ?, ACE ?) des filaments imprimés du plan affiché par défaut, comme la
    fenêtre les calcule (premier plan possible ; « Comme chargé » : cible de chaque filament ; hors mode tête : la
    tête est le numéro de voie de la bobine)."""
    r, info = dd["report"], dd.get("info") or {}
    gr, od = info.get("grams") or [], info.get("order") or []
    used = lambda t: (not gr and not od) or (t < len(gr) and gr[t] > 0) or t in od
    plans = r.get("plans") or {}
    if r.get("head_mode"):
        sel = next(k for k in ("loadout", "optimize", "layer", "color") if (plans.get(k) or {}).get("feasible"))
        tg = {t["id"]: t for t in r.get("targets") or []}
        out = []
        for m in plans[sel]["mapping"]:
            if not used(m["t"]):
                continue
            k = (tg.get(m.get("target_id")) or {}) if sel == "loadout" else m
            if k.get("kind") in ("ace", "pin"):
                out.append((k.get("head"), k["kind"] == "pin", k["kind"] == "ace"))
        return out
    sel = next(k for k in ("slicer", "optimize", "layer") if (plans.get(k) or {}).get("feasible"))
    return [(m["slot"]["slot"], False, True) for m in plans[sel]["mapping"] if used(m["t"]) and m.get("slot")]
