EXT = re.compile(r'^\s*(?:N[0-9]+\s*)?(?P<cmd>[a-zA-Z_][a-zA-Z0-9_]+)(?:\s+|$)(?P<args>[^#*;]*?)\s*(?:[#*;].*)?$')
def klipper(line):
    """(commande, paramètres) comme Klipper, None pour une ligne de commentaire ou vide."""
    s = line.split(";", 1)[0].strip()
    if not s:
        return None
    m = EXT.match(line)
    args = {}
    for a in m.group("args").split():
        k, v = a.split("=", 1)
        args[k.upper()] = v
    return m.group("cmd").upper(), args

