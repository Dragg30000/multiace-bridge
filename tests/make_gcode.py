"""Fabrique un G-code U1 8 couleurs proche d'un export OrcaSlicer (en-tete, start, changements d'outil, pied)."""
import random
random.seed(4)
COLS = ["#FFFFFF", "#000000", "#8D6E63", "#F48FB1", "#43A047", "#E53935", "#FDD835", "#1E88E5"]
TYPES = ["PLA"] * 8
def make(path, layers=60):
    L = ["; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.5.0", "; HEADER_BLOCK_END",
         "SET_PRINT_AUTO_BED_LEVELING ENABLE=1", "PRINT_START", "M104 T5 S140", "G28 X Y", "T5", "G90",
         "SM_PRINT_EXTRUDER_PREHEAT EXTRUDER=1 TEMP=140", "M109 S210 T5",
         "SM_PRINT_PREEXTRUDE_FILAMENT INDEX=5", "SM_PRINT_PREEXTRUDE_FILAMENT INDEX=1", "G1 X10 Y10 E5 F600"]
    cur = 5
    for layer in range(layers):
        L += [";LAYER_CHANGE", ";Z:%.2f" % (0.2 * (layer + 1)), "G1 Z%.2f" % (0.2 * (layer + 1))]
        tools = random.sample(range(8), 3 if layer < 40 else 2)
        for t in tools:
            if t != cur:
                L += ["; Change Tool%d -> Tool%d (layer %d)" % (cur, t, layer), "G91", "G1 Z1.5 F600", "G90",
                      "M109 S210 T%d" % t, "M400", "T%d" % t]
                cur = t
            L += ["G1 X%d Y%d E1.2 F3000" % (random.randint(10, 200), random.randint(10, 200)) for _ in range(5)]
    L += ["PRINT_END", "; filament used [mm] = " + ",".join("%.2f" % random.uniform(100, 900) for _ in COLS),
          "; CONFIG_BLOCK_START", "; filament_colour = " + ";".join(COLS), "; filament_type = " + ";".join(TYPES),
          "; nozzle_diameter = " + ",".join(["0.4"] * 8), "; CONFIG_BLOCK_END"]
    open(path, "w").write("\n".join(L) + "\n")
if __name__ == "__main__":
    make("eight.gcode"); print(open("eight.gcode").read().count("Change Tool"))
